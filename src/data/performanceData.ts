export type HealthStatus = 'fit' | 'modified' | 'high_risk' | 'injured';

export interface RehabMilestone {
  title: string;
  completed: boolean;
  targetDate?: string;
}

export interface ActiveInjury {
  id: string;
  playerId: string;
  playerName: string;
  playerNumber: number;
  position: string;
  injuryName: string;
  bodyRegion: 'hamstrings' | 'quadriceps' | 'knee' | 'adductor' | 'calf' | 'ankle' | 'shoulder' | 'back' | 'head';
  side: 'left' | 'right' | 'bilateral';
  severity: 'Mild (Grade 1)' | 'Moderate (Grade 2)' | 'Severe (Grade 3)';
  mechanism: 'Contact' | 'Non-contact sprint' | 'Overuse / Fatigue' | 'Twisting / Change of direction' | 'Contact / Bad landing tackle';
  diagnosisDate: string;
  targetReturnDate: string;
  daysSidelined: number;
  expectedDaysTotal: number;
  rehabPhase: 1 | 2 | 3 | 4; // 1: Acute/Protected, 2: Loading/Gym, 3: Pitch conditioning, 4: Team integration
  rehabPhaseTitle: string;
  progressPct: number;
  milestones: RehabMilestone[];
  treatmentProtocol: string[];
  physioAssigned: string;
  clearanceStatus: 'Restricted' | 'Gym Only' | 'Modified Pitch Drills' | 'Match Fit Pending Test';
  notes: string;
}

export interface PlayerTelemetry {
  playerId: string;
  name: string;
  number: number;
  position: 'Goalkeeper' | 'Defender' | 'Midfielder' | 'Forward';
  positionShort: 'GK' | 'DF' | 'MF' | 'FW';
  photoUrl?: string;
  status: HealthStatus;
  statusReason: string;

  // Physical & GPS Telemetry (Latest Match / Training)
  totalDistanceKm: number;
  highSpeedRunningM: number; // >19.8 km/h
  sprintDistanceM: number;   // >25.2 km/h
  topSpeedKmh: number;
  accelerations: number;     // >3.0 m/s²
  decelerations: number;     // <-3.0 m/s²
  playerLoadAU: number;      // Arbitrary Units (accelerometer load)

  // Physiological & Recovery Readiness
  readinessScore: number;    // 0 - 100%
  hrvRmssd: number;          // ms (Heart Rate Variability)
  restingHrBpm: number;      // bpm
  sleepHours: number;
  sleepEfficiencyPct: number;
  muscleSoreness: number;    // 1 (fresh) to 10 (extremely sore)
  fatigueScore: number;      // 1 to 10
  stressScore: number;       // 1 to 10
  hydrationUsg: number;      // Urine Specific Gravity (e.g. 1.012 optimal, >1.020 dehydrated)

  // Workload & ACWR (Acute:Chronic Workload Ratio)
  acuteWorkload: number;     // 7-day rolling load
  chronicWorkload: number;   // 28-day rolling average
  acwr: number;              // Acute:Chronic ratio
  acwrRisk: 'optimal' | 'elevated' | 'high_danger' | 'undertraining';

  // Medical History & Active Injury
  activeInjury?: ActiveInjury;
  injuryRiskScore: number;   // 1 to 100% predictive risk algorithm
  riskFactors: string[];
  pastInjuriesCount: number;
  lastFitnessTestScore: string; // e.g., "Yo-Yo IR2: 2,160m (Elite)"
}

